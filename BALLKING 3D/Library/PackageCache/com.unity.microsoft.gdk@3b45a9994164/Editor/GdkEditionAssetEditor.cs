using Unity.XGamingRuntime;
using UnityEngine;
using UnityEditor;

namespace Unity.Microsoft.GDK.Editor
{
    /// <summary>
    /// Custom editor for the GdkEditionAsset that provides a read-only inspector view of the GDK edition number.
    /// </summary>
    [CustomEditor(typeof(GdkEditionAsset))]
    internal class GdkEditionAssetEditor : UnityEditor.Editor
    {
        private SerializedProperty m_EditionNumberProperty;

        private void OnEnable()
        {
            m_EditionNumberProperty = serializedObject.FindProperty("m_EditionNumber");
        }

        public override void OnInspectorGUI()
        {
            EditorGUILayout.HelpBox(
                "This asset was auto-generated by the Microsoft API package. " +
                "It allows the GDK API wrappers to handle edition compatibility requirements at runtime and " +
                "should not be manually altered. There should be no reason to commit this file to source control " +
                "as it is generated/removed by the build pipeline.",
                MessageType.Info
            );

            EditorGUILayout.Space();

            using (new EditorGUI.DisabledGroupScope(true))
            {
                EditorGUILayout.PropertyField(m_EditionNumberProperty, new GUIContent("Edition Number"));
            }
        }
    }
}