using System;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace Unity.Microsoft.GDK.Tools.Editor
{
    internal static class GdkPlatformSettingsGenerator
    {
        public struct Options
        {
            public bool includeDefine  { get; set; }
            public string namespaceName { get; set; }
            public string sourceAssetPath { get; set; }

            public BuildTargetGroup targetGroup { get; set; }
        }

        public static string GenerateWrapperCode(GdkSettingsAsset asset, Options options = default)
        {
            if (asset == null)
                throw new ArgumentNullException(nameof(asset));

            if (string.IsNullOrEmpty(options.sourceAssetPath))
                options.sourceAssetPath = AssetDatabase.GetAssetPath(asset);

            StringBuilder sb = new StringBuilder();

            // Header
            sb.Append(MakeAutoGeneratedCodeHeader("com.unity.microsoft.gdk.tools:GdkPlatformSettingsGenerator",
                " ",
                options.sourceAssetPath));

            // using ...
            sb.Append($"using System;\n\n");

            // Begin namespace
            if (!string.IsNullOrEmpty(options.namespaceName))
                sb.Append($"namespace {options.namespaceName}\n{{\n");

            // Begin class
            sb.Append($"public static class GdkPlatformSettings\n{{\n");

            // Class Properties
            GdkSettingsAsset gdkSettings =  GdkSettingsProvider.LoadSettings();

            bool platformIncluded = false;

            // Add none WindowsPlayer platforms
            foreach (GdkSettingsAsset.PlatformGdkSettings platformSettings in gdkSettings.GetPlatformSettingsList())
            {
                if (platformSettings.runtimePlatform != RuntimePlatform.WindowsPlayer)
                {
                    if (platformSettings.targetMicrosoftGdk)
                    {
                        string compilerConditional = GDKPlatformManager.GetPlatformCompilerConditional(platformSettings.runtimePlatform);

                        if (string.IsNullOrEmpty(compilerConditional))
                            continue;

                        if (platformIncluded)
                        {
                            sb.Append($"#elif {compilerConditional}\n");
                        }
                        else
                        {
                            sb.Append($"#if {compilerConditional}\n");
                            platformIncluded = true;
                        }

                        if (platformSettings.gameConfigAsset)
                        {
                            sb.Append(MakeProperties(
                                platformSettings.gameConfigAsset.TitleId,
                                platformSettings.gameConfigAsset.SCID));
                        }
                        else
                        {
                            sb.Append($"    // A Microsoft Game Config (MGC) asset has not been configured for this platform (see GDK Settings).\n");
                        }
                    }
                }
            }

            bool windowsPlayerSettingsExist = gdkSettings.SettingsForRuntimePlatform(
                GDKPlatformManager.BuildTargetGroupToRuntimePlatform(BuildTargetGroup.Standalone), out var standaloneSettings);

            if (platformIncluded)
                sb.Append($"#else\n");

            if (windowsPlayerSettingsExist && standaloneSettings.targetMicrosoftGdk)
            {
                if (standaloneSettings.gameConfigAsset)
                {
                    sb.Append(MakeProperties(
                        standaloneSettings.gameConfigAsset.TitleId,
                        standaloneSettings.gameConfigAsset.SCID));
                }
                else
                {
                    sb.Append($"    // A Microsoft Game Config (MGC) asset has not been configured for this platform (see GDK Settings).\n");
                }
            }

            if (platformIncluded)
                sb.Append($"#endif\n");

            // End class
            sb.Append("}\n");

            // End namespace
            if (!string.IsNullOrEmpty(options.namespaceName))
                sb.Append("}\n");

            return sb.ToString();
        }

        // Updates the given file with wrapper code generated for the given action sets.
        // If the generated code is unchanged, does not touch the file.
        // Returns true if the file was touched, false otherwise.
        public static bool GenerateWrapperCode(string filePath, GdkSettingsAsset asset, Options options)
        {
            if (!Path.HasExtension(filePath))
                filePath += ".cs";

            // Generate code.
            var code = GenerateWrapperCode(asset, options);

            // Check if the code changed. Don't write if it hasn't.
            /*
            if (File.Exists(filePath))
            {
                var existingCode = File.ReadAllText(filePath);
                if (existingCode == code || existingCode.WithAllWhitespaceStripped() == code.WithAllWhitespaceStripped())
                    return false;
            }
             */


            // Write.
            CheckOut(filePath);
            File.WriteAllText(filePath, code);
            return true;
        }

        private static string MakeAutoGeneratedCodeHeader(string toolName, string toolVersion, string sourceFileName = null)
        {
            return
                  $"// ------------------------------------------------------------------------------\n"
                + $"//  <auto-generated>\n"
                + $"//    This code was auto-generated by:\n"
                + $"//        '{toolName}'\n"
                + $"//\n"
                + $"//    Changes to this file may cause incorrect behavior and will be lost when\n"
                + $"//    regenerated.\n"
                + $"// </auto-generated>\n"
                + $"// ------------------------------------------------------------------------------\n\n";
        }

        private static string MakeProperties(string gameConfigTitleId, string gameConfigScid, string gameConfigSandbox=null)
        {
            StringBuilder sb = new StringBuilder();

            string titleID = !string.IsNullOrEmpty(gameConfigTitleId) ? gameConfigTitleId : "";
            sb.Append($"    public static string gameConfigTitleId = \"{titleID}\";\n");

            string SCID = !string.IsNullOrEmpty(gameConfigScid) ? gameConfigScid : "";
            sb.Append($"    public static string gameConfigScid = \"{SCID}\";\n");

            string sandbox = !string.IsNullOrEmpty(gameConfigSandbox) ? gameConfigSandbox : "";
            sb.Append($"    [Obsolete(\"gameConfigSandbox will be removed in future releases. Please do not use.\", false)]\n");
            sb.Append($"    public static string gameConfigSandbox = \"{sandbox}\";\n");

            return sb.ToString();
        }

        private static string WithAllWhitespaceStripped(this string str)
        {
            var buffer = new StringBuilder();
            foreach (var ch in str)
                if (!char.IsWhiteSpace(ch))
                    buffer.Append(ch);
            return buffer.ToString();
        }

        private static void CheckOut(string path)
        {
            if (string.IsNullOrEmpty(path))
                throw new ArgumentNullException(nameof(path));

            // Make path relative to project folder.
            var projectPath = Application.dataPath;
            if (path.StartsWith(projectPath) && path.Length > projectPath.Length &&
                (path[projectPath.Length] == '/' || path[projectPath.Length] == '\\'))
                path = path.Substring(0, projectPath.Length + 1);

            AssetDatabase.MakeEditable(path);
        }
    }
}